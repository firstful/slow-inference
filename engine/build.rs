#![allow(clippy::vec_init_then_push)]

fn main() {
    let out_dir = std::env::var("OUT_DIR").unwrap();
    let spv_dir = std::path::Path::new(&out_dir).join("spv");
    std::fs::create_dir_all(&spv_dir).unwrap();

    let mut mod_lines = Vec::<String>::new();
    mod_lines.push("// Auto-generated by build.rs. Do not edit.".into());
    mod_lines.push("#[allow(unused_imports)]".into());
    mod_lines.push("pub fn load_all_pipelines(vk: &mut crate::vk::VulkanBackend) {".into());

    for entry in std::fs::read_dir("shaders").unwrap() {
        let entry = entry.unwrap();
        let path = entry.path();
        if !path.extension().is_some_and(|e| e == "comp") {
            continue;
        }
        let stem = path.file_stem().unwrap().to_str().unwrap().to_string();
        let spv_path = spv_dir.join(format!("{stem}.spv"));

        let status = std::process::Command::new("glslc")
            .arg("-fshader-stage=compute")
            .arg(&path)
            .arg("-o")
            .arg(&spv_path)
            .status()
            .unwrap_or_else(|e| panic!("glslc failed for {stem}: {e}"));
        assert!(status.success(), "glslc compile failed for {stem}");
        println!("cargo:rerun-if-changed={}", path.display());

        let spv_bytes = std::fs::read(&spv_path).unwrap();

        let hex_parts: Vec<String> = spv_bytes.iter().map(|b| format!("0x{b:02x}u8")).collect();
        let array_str = hex_parts.join(", ");

        let variant = match stem.as_str() {
            "q4_k_matvec" => "Q4K",
            "q8_0_matvec" => "Q8_0",
            "f32_matvec" => "F32",
            _ => continue,
        };

        let const_name = format!("SPV_{}", stem.to_uppercase());
        mod_lines.push(format!("const {}: &[u8] = &[{}];", const_name, array_str));
        mod_lines.push(format!(
            "    let _ = vk.load_pipeline(crate::vk::GpuQuantFormat::{variant}, {const_name});"
        ));
    }

    mod_lines.push("}".into());

    let rs_path = spv_dir.join("pipelines.rs");
    std::fs::write(&rs_path, mod_lines.join("\n")).unwrap();
}
