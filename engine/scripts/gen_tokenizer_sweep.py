#!/usr/bin/env python3
"""Generate tests/data/tokenizer_sweep.txt — the partition's adversarial corpus.

`tests/data/tokenizer_corpus.txt` is the project's main tokenizer corpus and is
shared with the SentencePiece path, so adding cases to it changes what the SPM
parity test and its `SPM_MERGE_ORDER_SENSITIVE` allowlist mean. This sweep is a
second, separate corpus aimed at one thing: the special-token partition
(`llama_vocab::impl::tokenizer_st_partition`), which runs *before* the
pre-tokenizer and is invisible on a vocabulary whose special tokens are all
CONTROL markers.

The shapes here are the ones that discriminate a partition from no partition:

* every literal-space run length from 0 to 30. OLMoE marks ids 50254..50276 —
  runs of 24 down to 2 — USER_DEFINED, so the interesting lengths are the ones
  *around* those boundaries: 1 (no token), 2..24 (a token), 25+ (greedy
  longest-first consumption with a remainder).
* a run with text on either side and on both sides, so a wrong fragment order
  or a dropped remainder shows up.
* whitespace that is not a space: tabs and newlines are not in the vocabulary,
  so a run of them must fall through to the pre-tokenizer unchanged.
* the vocabulary's other USER_DEFINED tokens (`|||IP_ADDRESS|||` and friends),
  which are cut on even though they contain no whitespace.
* CONTROL tokens (`<s>`, `<pad>`, the empty EOG marker), which under
  `parse_special = false` must *not* be cut on — the case that would silently
  become wrong if `parse_special` were ever flipped to true.
* non-ASCII adjacent to runs, because the partition works on raw bytes and the
  pre-tokenizer on codepoints.

Usage: scripts/gen_tokenizer_sweep.py > tests/data/tokenizer_sweep.txt
"""

import sys

CASES: list[tuple[str, str]] = []


def add(name: str, text: str) -> None:
    CASES.append((name, text))


# 1. Bare runs, 0..30 spaces. `run00` is the empty string, which llama.cpp
#    returns zero tokens for.
for n in range(0, 31):
    add(f"run{n:02d}", " " * n)

# 2. A run with a word after it: the run becomes its own token and the word
#    keeps no leading space.
for n in (1, 2, 3, 12, 24, 25, 26):
    add(f"run{n:02d}_then_word", " " * n + "word")

# 3. A run with a word before it.
for n in (1, 2, 3, 24, 25):
    add(f"word_then_run{n:02d}", "word" + " " * n)

# 4. Runs on both sides: two fragments, two special tokens.
for n in (2, 3, 6, 13):
    add(f"word_run{n:02d}_word", "a" + " " * n + "b")
add("two_runs", "a  b   c")

# 5. Runs inside code-shaped text, where a newline is also present.
add("code_indent", "def f(x):\n    return x ** 2")
add("code_deep_indent", "if x:\n" + " " * 24 + "pass\n")
add("code_tabs", "if x:\n\t\tpass")
add("run_then_newline", "  \n  word")
add("newline_then_run", "\n  word")
add("trailing_run_then_newline", "word  \n")

# 6. Whitespace that is not a space: no vocabulary token matches, so these must
#    go through the pre-tokenizer unchanged.
add("tab_run", "\t\t")
add("tab_then_spaces", "\t  x")
add("newline_run", "\n\n\n")
add("mixed_ws", " \t\n  ")

# 7. USER_DEFINED PII sentinels: cut on, and the whole prompt becomes one id.
add("pii_ip", "|||IP_ADDRESS|||")
add("pii_email", "|||EMAIL_ADDRESS|||")
add("pii_phone", "|||PHONE_NUMBER|||")
add("pii_embedded", "mail me at |||EMAIL_ADDRESS||| tomorrow")
add("pii_after_run", "  |||IP_ADDRESS|||")

# 8. CONTROL tokens. Under parse_special = false these are pre-tokenized, not
#    emitted, so the ids here are several tokens rather than one.
add("control_bos", "<s>")
add("control_bos_inline", "a <s> b")
add("control_pad", "<pad>")
add("control_bos_between_runs", "  <s>  ")
add("control_tool_call", "<tool_call>")
add("control_fim", "<|fim_prefix|>x")

# 9. Non-ASCII next to runs: the partition is byte-wise, the pre-tokenizer is
#    codepoint-wise, and this is where the two disagree if either is wrong.
add("run_then_emoji", "  \U0001f600")
add("emoji_then_run", "\U0001f600  ")
add("run_then_cjk", "  你好")
add("cjk_then_run", "你好  ")
add("run_then_zwj", "  \U0001f468‍\U0001f469")
add("accented_then_run", "café  naïve")


def escape(text: str) -> str:
    out = []
    for ch in text:
        if ch == "\\":
            out.append("\\\\")
        elif ch == "\t":
            out.append("\\t")
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\r":
            out.append("\\r")
        elif ord(ch) < 0x20 or ord(ch) == 0x7F:
            out.append(f"\\x{ord(ch):02x}")
        else:
            out.append(ch)
    return "".join(out)


def main() -> None:
    names = [n for n, _ in CASES]
    assert len(set(names)) == len(names), "duplicate case name"
    w = sys.stdout.write
    w("# Special-token-partition sweep. Generated by scripts/gen_tokenizer_sweep.py;\n")
    w("# edit the generator, not this file. The reference ids come from\n")
    w("# llama.cpp's own llama_tokenize via scripts/gen_ref_tokens.sh.\n")
    for name, text in CASES:
        w(f"{name}\t{escape(text)}\n")


if __name__ == "__main__":
    main()