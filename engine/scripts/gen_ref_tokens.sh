#!/usr/bin/env bash
# Rebuild tests/data/ref_tokens/*.ref from llama.cpp's own tokenizer.
#
# Each .ref holds, for every case in a corpus file, the exact token ids
# llama.cpp produces for all four combinations of
# `llama_tokenize(vocab, text, add_special, parse_special)`, plus the piece
# strings. engine/tests/tokenizer_parity.rs replays the same corpus through our
# own tokenizer and demands identical ids.
#
# Two corpora are produced, and the difference is why there are two:
#
#   tokenizer_corpus.txt    the main corpus, shared by the BPE and SentencePiece
#                           tests. Broad, and its exact-set allowlists
#                           (`SPM_MERGE_ORDER_SENSITIVE`) mean a new case is a
#                           decision.
#   tokenizer_sweep.txt     adversarial cases for the special-token partition
#                           alone (generated by scripts/gen_tokenizer_sweep.py).
#                           Whitespace runs of every length 0..30, USER_DEFINED
#                           PII sentinels, CONTROL tokens, runs next to non-ASCII.
#
# This is the tokenizer counterpart of scripts/gen_ref_logits.sh: it is the
# only step that needs a built llama.cpp. Once the .ref files exist, `cargo test`
# runs the whole parity suite with no C toolchain and no llama.cpp checkout.
#
# Usage: scripts/gen_ref_tokens.sh [model.gguf ...]
#   With no arguments, regenerates the .ref for every GGUF named below. Tiny-Moe
#   is an SPM vocabulary and gets the main corpus only: the sweep exists to
#   attack the *BPE* partition, where a vocabulary marks runs of literal spaces
#   USER_DEFINED. Tiny-MoE has no USER_DEFINED token at all, so 75 of its sweep
#   cases would be the main corpus restated.
set -euo pipefail

LLAMA_CPP="${LLAMA_CPP:-$HOME/llama.cpp}"
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
REPO="$(cd "$HERE/.." && pwd)"

MAIN_CORPUS="$HERE/tests/data/tokenizer_corpus.txt"
SWEEP_CORPUS="$HERE/tests/data/tokenizer_sweep.txt"

# model basename -> the corpora it is checked against
MAIN_ONLY_MODELS="Tiny-Moe.Q4_K_M"

if [ ! -f "$LLAMA_CPP/build/bin/libllama.so" ]; then
    echo "no libllama.so under $LLAMA_CPP/build/bin — build llama.cpp first" >&2
    exit 1
fi

mkdir -p "$HERE/tests/data/ref_tokens"

BIN="$(mktemp -d)/gen_ref_tokens"
trap 'rm -rf "$(dirname "$BIN")"' EXIT
gcc -O2 -std=c11 -o "$BIN" \
    -I"$LLAMA_CPP/include" \
    -I"$LLAMA_CPP/ggml/include" \
    "$HERE/tools/gen_ref_tokens.c" \
    -L"$LLAMA_CPP/build/bin" -lllama -lggml -lggml-base -lm \
    -Wl,-rpath,"$LLAMA_CPP/build/bin"

if [ "$#" -gt 0 ]; then
    MODELS=("$@")
else
    MODELS=(
        "$REPO/models/qwen2.5-3b-instruct-q4_k_m.gguf"
        "$REPO/models/OLMoE-1B-7B-Instruct-Q4_K_M.gguf"
        "$REPO/models/Tiny-Moe.Q4_K_M.gguf"
    )
fi

for gguf in "${MODELS[@]}"; do
    if [ ! -f "$gguf" ]; then
        echo "missing $gguf" >&2
        exit 1
    fi
    name="$(basename "$gguf" .gguf)"
    CORPORA=("$MAIN_CORPUS:")
    case " $MAIN_ONLY_MODELS " in
        *" $name "*) ;;
        *) CORPORA+=("$SWEEP_CORPUS:.sweep") ;;
    esac
    for entry in "${CORPORA[@]}"; do
        corpus="${entry%:*}"
        suffix="${entry##*:}"
        if [ ! -f "$corpus" ]; then
            echo "missing corpus $corpus — regenerate it first" >&2
            exit 1
        fi
        out="$HERE/tests/data/ref_tokens/$name$suffix.ref"
        # llama.cpp is chatty on stderr; only its own summary line is interesting.
        "$BIN" "$gguf" "$corpus" "$out" 2>&1 | grep -E '^gen_ref_tokens:' || true
        echo "wrote $out"
    done
done
