#!/usr/bin/env python3
"""Emit src/quant_tables.rs from llama.cpp's ggml-common.h.

The iq*_grid / ksigns / kmask tables are `static const` inside
ggml-common.h, so they cannot be linked against — we parse the header
instead. Regenerate with:

    python3 engine/scripts/gen_quant_tables.py

Set $LLAMA_CPP to point at a llama.cpp checkout other than ~/llama.cpp.
"""
import os
import re
import sys

LLAMA_CPP = os.environ.get("LLAMA_CPP", os.path.expanduser("~/llama.cpp"))
HEADER = os.path.join(LLAMA_CPP, "ggml", "src", "ggml-common.h")
OUT = os.path.join(
    os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "src", "quant_tables.rs"
)

# name -> (rust name, rust element type, count expression or literal)
WANTED = [
    ("kmask_iq2xs", "KMASK_IQ2XS", "u8", 8),
    ("ksigns_iq2xs", "KSIGNS_IQ2XS", "u8", 128),
    ("kvalues_iq4nl", "KVALUES_IQ4NL", "i8", 16),
    ("iq2xxs_grid", "IQ2XXS_GRID", "u64", 256),
    ("iq2xs_grid", "IQ2XS_GRID", "u64", 512),
    ("iq2s_grid", "IQ2S_GRID", "u64", 1024),
    ("iq3xxs_grid", "IQ3XXS_GRID", "u32", 256),
    ("iq3s_grid", "IQ3S_GRID", "u32", 512),
    ("iq1s_grid", "IQ1S_GRID", "u64", "NGRID_IQ1S"),
]


def defines(text):
    out = {}
    for m in re.finditer(r"#define\s+(\w+)\s+(\S+)", text):
        out[m.group(1)] = m.group(2)
    return out


def table_body(text, ctype, name):
    """Return the list of literal tokens inside GGML_TABLE_BEGIN(ctype, name, ...)."""
    start = re.search(
        r"GGML_TABLE_BEGIN\(\s*%s\s*,\s*%s\s*," % (re.escape(ctype), re.escape(name)), text
    )
    if start is None:
        raise SystemExit("table %s not found in %s" % (name, HEADER))
    end = text.index("GGML_TABLE_END()", start.end())
    body = text[start.end() : end]
    # skip the size argument: `NGRID_IQ1S)` (or `8)`) before the `{`
    body = body[body.index(")") + 1 :]
    return [tok for tok in body.replace("\n", " ").split(",") if tok.strip()]


def resolve_count(count, defs):
    if isinstance(count, int):
        return count
    expr = count
    for _ in range(8):
        m = re.fullmatch(r"(\w+)\s*(?:/\s*(\d+))?", expr)
        if not m or m.group(1) not in defs:
            break
        expr = defs[m.group(1)]
        if m.group(2):
            expr = "(%s)/%s" % (expr, m.group(2))
    return int(eval(expr, {"__builtins__": {}}, defs))  # noqa: S307 - fixed input


def fmt(tok, rtype):
    tok = tok.strip()
    if rtype == "i8":
        return tok
    if rtype in ("u8",):
        return tok
    if rtype in ("u32", "u64"):
        low = tok.lower()
        if low.startswith("0x"):
            return "%s%s" % (low, rtypelit[rtype])
        return low
    raise ValueError(rtype)


rtypelit = {"u8": "u8", "i8": "i8", "u32": "u32", "u64": "u64"}


def main():
    with open(HEADER, encoding="utf-8") as f:
        text = f.read()
    defs = defines(text)

    chunks = [
        "//! Constant tables for the i-quants and TQ quants.",
        "//!",
        "//! GENERATED by engine/scripts/gen_quant_tables.py from",
        "//! %s — do not edit by hand." % HEADER,
        "//!",
        "//! These are `static const` in C, so they cannot be linked against;",
        "//! the generator parses the header instead.",
        "",
        "#![allow(clippy::unreadable_literal)]",
        "",
    ]
    # macros we depend on, resolved from the header
    ngrid = resolve_count("NGRID_IQ1S", defs)
    iq1s_delta = float(defs["IQ1S_DELTA"].rstrip("f"))
    chunks.append("/// QK_K from ggml-common.h")
    chunks.append("pub const QK_K: usize = %d;" % resolve_count("QK_K", defs))
    chunks.append("/// QK4_NL from ggml-common.h")
    chunks.append("pub const QK4_NL: usize = %d;" % resolve_count("QK4_NL", defs))
    chunks.append("/// IQ1S_DELTA from ggml-common.h")
    chunks.append("pub const IQ1S_DELTA: f32 = %sf32;" % repr(iq1s_delta))
    chunks.append("")

    ctype_for = {"u8": "uint8_t", "i8": "int8_t", "u32": "uint32_t", "u64": "uint64_t"}

    for c_name, r_name, rtype, count in WANTED:
        n = resolve_count(count, defs)
        toks = table_body(text, ctype_for[rtype], c_name)
        if len(toks) != n:
            raise SystemExit(
                "%s: header has %d entries, expected %d" % (c_name, len(toks), n)
            )
        body = ", ".join(fmt(t, rtype) for t in toks)
        lines = []
        cur = "    "
        for tok in toks:
            piece = fmt(tok, rtype) + ", "
            if len(cur) + len(piece) > 96:
                lines.append(cur.rstrip())
                cur = "    "
            cur += piece
        lines.append(cur.rstrip().rstrip(","))
        chunks.append("pub const %s: [%s; %d] = [" % (r_name, rtype, n))
        chunks.extend(lines)
        chunks.append("];")
        chunks.append("")

    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(chunks).rstrip() + "\n")
    print("wrote %s (%d lines)" % (OUT, len(chunks)))


if __name__ == "__main__":
    main()
