//! Forward-pass parity against llama.cpp and against exact float64 math.
//!
//! The parity project stalled for a long time on "we have no GGUF for
//! architecture X, so nothing can be validated". That is no longer true, and
//! this test is what makes it true *durably* rather than as a one-off shell
//! session.
//!
//! There are two references per architecture, and they answer different
//! questions:
//!
//! * `<arch>.ref` — llama.cpp's own `llama_decode` output, via
//!   `tools/gen_ref_logits.c`. This is the *named* parity oracle: it proves we
//!   compute the same function llama.cpp does.
//! * `<arch>.f64.ref` — an independent float64 forward pass, via
//!   `scripts/arbitrate_logits.py`. This is the *tight* oracle.
//!
//! Both are needed because llama.cpp's forward pass is not numerically exact,
//! and measuring that was the point of adding the second one. Against the
//! float64 reference, llama.cpp lands 2e-4..9.6e-4 away from exact while the
//! engine lands 3e-7..6e-7 — llama.cpp is the *less* accurate of the two by
//! three orders of magnitude, because it takes three precision shortcuts by
//! default: flash attention casts K and V to float16
//! (`llama-graph.cpp:2530`), the KV cache defaults to float16
//! (`llama-context.cpp:3508`), and GELU is evaluated through a 64K-entry
//! float16 lookup table (`GGML_GELU_FP16`, `ggml-cpu/vec.h:46`). `gen_ref_logits`
//! disables the first two so it stops being the limiting factor; the third is
//! inside ggml's kernel and cannot be turned off, which is why the GELU
//! architectures get a looser floor against `.ref`.
//!
//! Consequence: a gate written against `.ref` alone would sit at 1e-3 and miss a
//! subtly wrong activation constant. Against `.f64.ref` the same bug is ~1e-6,
//! four orders of magnitude above the engine's actual rounding, so it is caught.
//!
//! Fixtures are tiny, F32, and pseudo-random, generated by
//! `scripts/generate_synthetic_fixtures.py`. A degenerate fixture (all ones,
//! identity) can pass by accident; pseudo-random weights expose any
//! transposition, mis-slicing, or missing scale factor. They are checked in
//! under `tests/data/fixtures/`. If a fixture is absent the case reports a
//! skip rather than failing, so the suite still runs on a checkout that does not
//! carry them.

use std::path::{Path, PathBuf};
use std::process::Command;

use slow_inference::model::Model;

/// Vocab width of every generated fixture. The gate below is written in terms
/// of this so a fixture with a different vocab fails loudly rather than
/// silently comparing a truncated row.
const N_VOCAB: usize = 128;

/// Prompt used for every fixture: eight distinct, non-sequential token ids.
/// Non-sequential on purpose — a fixture that only ever sees ids 0..7 in order
/// would let a positional-embedding bug cancel out.
const PROMPT: &[usize] = &[3, 17, 42, 99, 7, 61, 128 - 1, 24];

const TOP_K: usize = 5;

/// Relative L2 error against the float64 reference, per architecture.
///
/// The engine's measured error is 3e-7..6e-7 on every fixture, so 1e-5 leaves
/// roughly an order of magnitude of headroom for platform-dependent f32
/// summation order while still sitting four orders of magnitude below the
/// error a wrong activation constant produces. Set deliberately in one place so
/// it is obvious these are not arbitrary.
const F64_REL_L2: f64 = 1e-5;

/// Relative L2 error against llama.cpp's own output, per architecture.
///
/// llama/qwen2 have no lossy activation, so their reference is exact to ~2e-7
/// and the same tight gate applies. gpt2 (and, by extension, falcon / gemma3,
/// which also route through the float16 GELU table) cannot reach that: the
/// table alone costs ~3e-4, measured by modelling it in
/// `arbitrate_logits.py --f16-gelu`, which reproduces llama.cpp to 1.5e-7. That
/// is a floor in the *reference*, not slack in our implementation — the f64
/// gate above is what actually constrains GELU architectures.
const LLAMA_REL_L2_EXACT: f64 = 1e-5;
const LLAMA_REL_L2_F16_GELU: f64 = 2e-3;

/// Architectures whose reference is degraded by the float16 GELU table.
const F16_GELU_ARCHS: &[&str] = &["gpt2", "falcon", "gemma3"];

struct Ref {
    n_vocab: usize,
    rows: Vec<Vec<f32>>,
}

fn fixture_dir() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/data/fixtures")
}

fn ref_path(arch: &str) -> PathBuf {
    fixture_dir().join(format!("{arch}.ref"))
}

fn f64_path(arch: &str) -> PathBuf {
    fixture_dir().join(format!("{arch}.f64.ref"))
}

fn llama_gate(arch: &str) -> f64 {
    if F16_GELU_ARCHS.contains(&arch) {
        LLAMA_REL_L2_F16_GELU
    } else {
        LLAMA_REL_L2_EXACT
    }
}

fn rel_l2(a: &[f32], b: &[f32]) -> f64 {
    let (mut num, mut den) = (0f64, 0f64);
    for (x, y) in a.iter().zip(b.iter()) {
        num += (*x as f64 - *y as f64).powi(2);
        den += *y as f64 * *y as f64;
    }
    if den == 0.0 {
        return 0.0;
    }
    num.sqrt() / den.sqrt()
}

fn load_ref(path: &Path) -> Ref {
    let buf = std::fs::read(path).unwrap_or_else(|e| panic!("read {}: {e}", path.display()));
    assert_eq!(&buf[..8], b"SLDREFLG", "{}: bad magic", path.display());
    let u32at = |off: usize| u32::from_le_bytes(buf[off..off + 4].try_into().unwrap());
    assert_eq!(u32at(8), 1, "{}: unsupported version", path.display());
    let n_tok = u32at(12) as usize;
    let mut off = 16;
    let tokens: Vec<i32> = buf[off..off + 4 * n_tok]
        .as_chunks::<4>()
        .0
        .iter()
        .map(|c| i32::from_le_bytes(*c))
        .collect();
    off += 4 * n_tok;
    let n_vocab = u32at(off) as usize;
    off += 4;
    assert_eq!(
        buf.len() - off,
        n_tok * n_vocab * 4,
        "{}: truncated logits block",
        path.display()
    );
    assert_eq!(
        tokens,
        PROMPT.iter().map(|&t| t as i32).collect::<Vec<_>>(),
        "{}: reference was generated for a different prompt; regenerate with \
         scripts/gen_ref_logits.sh",
        path.display()
    );
    let rows = (0..n_tok)
        .map(|i| {
            let base = off + i * n_vocab * 4;
            buf[base..base + n_vocab * 4]
                .as_chunks::<4>()
                .0
                .iter()
                .map(|c| f32::from_le_bytes(*c))
                .collect()
        })
        .collect();
    Ref { n_vocab, rows }
}

fn cosine(a: &[f32], b: &[f32]) -> f64 {
    let (mut dot, mut na, mut nb) = (0f64, 0f64, 0f64);
    for (x, y) in a.iter().zip(b.iter()) {
        dot += *x as f64 * *y as f64;
        na += *x as f64 * *x as f64;
        nb += *y as f64 * *y as f64;
    }
    if na == 0.0 || nb == 0.0 {
        return 0.0;
    }
    dot / (na.sqrt() * nb.sqrt())
}

fn argmax(a: &[f32]) -> usize {
    a.iter()
        .enumerate()
        .max_by(|(_, x), (_, y)| x.partial_cmp(y).unwrap())
        .map(|(i, _)| i)
        .unwrap()
}

fn top_k_set(a: &[f32], k: usize) -> Vec<usize> {
    let mut idx: Vec<usize> = (0..a.len()).collect();
    idx.sort_by(|&i, &j| a[j].partial_cmp(&a[i]).unwrap());
    idx.truncate(k);
    idx.sort_unstable();
    idx
}

/// Architectures with a checked-in fixture + both references.
///
/// deepseek2 is the first architecture here whose forward pass is *not* the
/// llama/qwen2 shape: split low-rank Q with a middle RMSNorm, a per-row
/// nope/rope split where only the rope half is rotated, absorbed MLA attention
/// that collapses GQA to MQA, and a dense-lead FFN followed by MoE blocks with a
/// shared expert. Getting the MLA latent cache right is the whole point of
/// ROADMAP C7, and until now it had only a unit test.
///
/// gemma3 adds the layer-dependent parts: a sliding-window / global split that
/// has to be right per layer, embeddings scaled by `sqrt(n_embd)`, a QK-norm
/// whose weight vector is shared by every head, post-norms applied to the branch
/// output rather than to the residual sum, and an attention output that is
/// `n_head * key_length` wide rather than `embedding_length` wide.
///
/// Two of gemma3's properties are only visible from the *second* position on and
/// this file's prompt has eight tokens because of them:
/// * RoPE pairing. llama.cpp uses NEOX (pairs offset by `n_rot/2`) for gemma3,
///   which is not the pairing ggml calls `NORM`. At position 0 the rotation is
///   the identity, so a single-token prompt cannot tell the two apart.
/// * `f_attention_scale`. It multiplies the attention logits, so with one key in
///   the cache the softmax returns 1 regardless of what it is.
///
/// `llama-moe` is the same architecture as `llama` with a MoE FFN and **two of
/// four experts used**, so only the case name differs — see [`gguf_arch`].
///
/// It exists because a `llama`-arch MoE model that routes to every expert
/// cannot observe `norm_w`, the renormalisation of the selected experts'
/// weights by their own sum. llama.cpp's `llama` arch always applies it
/// (llama.cpp:209 passes a literal `true`, not a metadata flag), and the only
/// such file on disk is Tiny-MoE at 2 of 2, where the division is a no-op up to
/// one ulp. `scripts/arb_route_power.py` measures what this fixture buys:
/// all 24 of its routing decisions have a renormalisation factor of at least
/// 1.21 across all six unordered expert pairs, and deleting `norm_w` moves the
/// logits by 4.0e-1 — five orders of magnitude past `F64_REL_L2`.
///
/// `deepseek2-fused` is `deepseek2` again, with the expert gate and up
/// projections stored as llama.cpp's *preferred* single tensor
/// `ffn_gate_up_exps` = `{n_embd, n_ff_exp*2, n_expert}` instead of the split
/// `ffn_{gate,up}_exps` pair. `create_tensor_gate_up_exps`
/// (llama-model.cpp:2881) tries the fused tensor first, so a GGUF converted
/// with `convert_hf_to_gguf.py --fuse-gate-up-exps` has *only* the fused tensor
/// and an engine that reads split-only cannot load it at all. The weights are
/// bit-identical to `synthetic-deepseek2.gguf` (see `gen_deepseek2`), which is
/// what makes [`the_fused_and_split_expert_forms_agree_bit_for_bit`] an identity
/// rather than a comparison of two unrelated models.
const CASES: &[&str] = &[
    "llama",
    "qwen2",
    "gpt2",
    "deepseek2",
    "deepseek2-fused",
    "deepseek2-normw",
    "gemma3",
    "llama-moe",
    "llama-moe-wscale",
];

/// `general.architecture` inside the fixture for a case name.
///
/// Equal to the case name for every case but the two that deliberately reuse an
/// existing architecture: a MoE routing fixture is `llama` with
/// `expert_count > 0`, and the fused expert fixture is `deepseek2` with one
/// tensor renamed. Giving either its own arch key would test the parser rather
/// than the thing under test.
fn gguf_arch(case: &str) -> &str {
    match case {
        "llama-moe" => "llama",
        "llama-moe-wscale" => "llama",
        "deepseek2-fused" => "deepseek2",
        "deepseek2-normw" => "deepseek2",
        other => other,
    }
}

#[test]
fn forward_matches_llama_cpp_logits() {
    let mut ran = 0;
    let mut skipped = Vec::new();

    for &arch in CASES {
        let gguf = fixture_dir().join(format!("synthetic-{arch}.gguf"));
        let llamap = ref_path(arch);
        let f64p = f64_path(arch);
        if !gguf.exists() || !llamap.exists() || !f64p.exists() {
            skipped.push(arch);
            continue;
        }
        ran += 1;

        let reference = load_ref(&llamap);
        let exact = load_ref(&f64p);
        assert_eq!(
            reference.n_vocab, N_VOCAB,
            "{arch}: fixture vocab changed; regenerate the references"
        );
        assert_eq!(
            reference.rows.len(),
            exact.rows.len(),
            "{arch}: reference row counts differ"
        );

        let m = Model::open(gguf.to_str().unwrap())
            .unwrap_or_else(|e| panic!("open {}: {e}", gguf.display()));
        assert_eq!(m.arch, gguf_arch(arch), "{arch}: fixture arch mismatch");
        let rows = m
            .prefill_logits(PROMPT)
            .unwrap_or_else(|e| panic!("{arch}: prefill failed: {e}"));
        assert_eq!(rows.len(), PROMPT.len(), "{arch}: wrong number of rows");
        assert!(
            rows[0].len() >= N_VOCAB,
            "{arch}: output projection is narrower than the vocab"
        );

        let llama_gate = llama_gate(arch);
        let mut worst_llama = 0f64;
        let mut worst_f64 = 0f64;

        for (pos, ((got, want), truth)) in rows
            .iter()
            .zip(reference.rows.iter())
            .zip(exact.rows.iter())
            .enumerate()
        {
            let got = &got[..N_VOCAB];
            let e_llama = rel_l2(got, want);
            let e_f64 = rel_l2(got, truth);
            worst_llama = worst_llama.max(e_llama);
            worst_f64 = worst_f64.max(e_f64);
            let cos = cosine(got, truth);

            // The tight gate. This is the one that catches a wrong activation
            // constant; the engine's own rounding is ~5e-7 here. The named
            // oracle's distance is in the message because when this fires, "which
            // of the three implementations is wrong" is the next question and the
            // answer is visible in the number next to it.
            assert!(
                e_f64 <= F64_REL_L2,
                "{arch} pos {pos}: rel L2 vs float64 {e_f64:.3e} > {F64_REL_L2:.0e} \
                 (vs llama.cpp: {e_llama:.3e})"
            );
            // The named oracle. Proves we compute llama.cpp's function, within
            // whatever precision llama.cpp itself chose to evaluate it in.
            assert!(
                e_llama <= llama_gate,
                "{arch} pos {pos}: rel L2 vs llama.cpp {e_llama:.3e} > {llama_gate:.0e}"
            );
            assert_eq!(
                argmax(got),
                argmax(truth),
                "{arch} pos {pos}: argmax disagrees with exact math"
            );
            assert_eq!(
                top_k_set(got, TOP_K),
                top_k_set(truth, TOP_K),
                "{arch} pos {pos}: top-{TOP_K} disagrees with exact math"
            );
            assert!(
                cos >= 1.0 - 1e-9,
                "{arch} pos {pos}: cosine vs exact {cos:.12}"
            );
        }
        eprintln!("ref_parity {arch:>6}: worst rel L2 llama={worst_llama:.2e} f64={worst_f64:.2e}");
    }

    if ran == 0 {
        eprintln!(
            "ref_parity: skipped — no fixtures under {}. Generate them with\n  \
             python3 scripts/generate_synthetic_fixtures.py --arch <arch> --out \
             engine/tests/data/fixtures/synthetic-<arch>.gguf\n  \
             ./scripts/gen_ref_logits.sh",
            fixture_dir().display()
        );
    } else if !skipped.is_empty() {
        eprintln!("ref_parity: {skipped:?} skipped (fixture or reference missing)");
    }
}

/// The fused and split expert tensor containers are the same function.
///
/// `synthetic-deepseek2-fused.gguf` is `synthetic-deepseek2.gguf` with
/// `ffn_gate_exps`/`ffn_up_exps` replaced by `ffn_gate_up_exps` — the same weight
/// bytes, concatenated gate-rows-first-then-up-rows per expert, which is what
/// `convert_hf_to_gguf.py --fuse-gate-up-exps` writes. Both forms must produce
/// the same logits, and the tolerance here is **zero**: `Model::expert` resolves
/// the row layout before doing any arithmetic, so the two forms run the same
/// sequence of the same float operations over the same values.
///
/// A tolerance would be the wrong tool. It would pass for an engine that read the
/// fused rows in the wrong order and got a *different but nearby* answer, and the
/// order really is wrong-able: a fixture generated with `np.concatenate([up, gate])`
/// instead of `[gate, up]` changes llama.cpp's own logits, so the two orders are
/// not interchangeable by accident.
///
/// The two references are checked to agree too, and separately from the engine —
/// llama.cpp's split and fused logits for these two files are byte-identical
/// (`gen_ref_logits.sh`), which is the upstream fact this test is built on.
#[test]
fn the_fused_and_split_expert_forms_agree_bit_for_bit() {
    let split = fixture_dir().join("synthetic-deepseek2.gguf");
    let fused = fixture_dir().join("synthetic-deepseek2-fused.gguf");
    if !split.exists() || !fused.exists() {
        eprintln!(
            "the_fused_and_split_expert_forms_agree_bit_for_bit: skipped (fixture missing); \
             generate with scripts/generate_synthetic_fixtures.py --arch deepseek2 \
             and --arch deepseek2-fused"
        );
        return;
    }

    let a = Model::open(split.to_str().unwrap()).unwrap();
    let b = Model::open(fused.to_str().unwrap()).unwrap();
    let rows_split = a.prefill_logits(PROMPT).unwrap();
    let rows_fused = b.prefill_logits(PROMPT).unwrap();

    assert_eq!(
        rows_split.len(),
        rows_fused.len(),
        "the two fixtures produced a different number of rows"
    );
    // Compare the raw bits, not the values: `1.0 == 1.0` would also hold for two
    // different NaN payloads and would say nothing about the arithmetic.
    for (pos, (x, y)) in rows_split.iter().zip(rows_fused.iter()).enumerate() {
        assert_eq!(
            x.len(),
            y.len(),
            "pos {pos}: split has {} logits, fused has {}",
            x.len(),
            y.len()
        );
        assert_eq!(
            x.iter().map(|f| f.to_bits()).collect::<Vec<_>>(),
            y.iter().map(|f| f.to_bits()).collect::<Vec<_>>(),
            "pos {pos}: fused ffn_gate_up_exps gave different logits than the split \
             ffn_{{gate,up}}_exps"
        );
    }

    // The same identity, stated once more against *llama.cpp* rather than against
    // ourselves -- otherwise a shared misreading of the fusion order would cancel.
    for (name, a, b) in [
        (
            "llama.cpp",
            ref_path("deepseek2"),
            ref_path("deepseek2-fused"),
        ),
        (
            "float64",
            f64_path("deepseek2"),
            f64_path("deepseek2-fused"),
        ),
    ] {
        if !a.exists() || !b.exists() {
            eprintln!("the_fused_and_split_expert_forms_agree_bit_for_bit: {name} refs missing");
            continue;
        }
        let (x, y) = (std::fs::read(&a).unwrap(), std::fs::read(&b).unwrap());
        assert_eq!(
            x, y,
            "{name}: llama.cpp/arbiter disagree between the fused and split fixtures -- \
             one of them is being read with the wrong row order"
        );
    }
}

/// The fixtures must be F32. If someone regenerates them quantized, the
/// tolerance gate above silently loosens by orders of magnitude and stops
/// being an architecture test, so assert the property the gate depends on.
#[test]
fn fixtures_are_f32() {
    let mut checked = 0;
    for &arch in CASES {
        let gguf = fixture_dir().join(format!("synthetic-{arch}.gguf"));
        if !gguf.exists() {
            continue;
        }
        checked += 1;
        let m = Model::open(gguf.to_str().unwrap()).unwrap();
        let info =
            m.gf.tensors
                .get("token_embd.weight")
                .unwrap_or_else(|| panic!("{arch}: no token_embd.weight"));
        assert_eq!(
            info.dtype, 0,
            "{arch}: fixture is not F32 (ggml type {} != 0) — regenerate it, or \
             the tolerance gate in forward_matches_llama_cpp_logits stops being an \
             architecture test",
            info.dtype
        );
    }
    if checked == 0 {
        eprintln!("fixtures_are_f32: skipped (no fixtures present)");
    }
}

/// Guard against the prompt in this file drifting away from the one baked into
/// `tests/data/fixtures/*.ref`. `load_ref` asserts it too, but this reports the
/// regeneration command instead of a panic deep inside parsing.
#[test]
fn prompt_matches_checked_in_references() {
    let mut checked = 0;
    for &arch in CASES {
        let refp = ref_path(arch);
        if !refp.exists() {
            continue;
        }
        checked += 1;
        load_ref(&refp);
    }
    if checked == 0 {
        eprintln!("prompt_matches_checked_in_references: skipped (no references present)");
    }
}

/// The float64 oracle must still be able to *reproduce* the checked-in
/// `.f64.ref` files.
///
/// The suite reads those files rather than regenerating them, which is what makes
/// it fast and llama.cpp-free — and which means nothing notices when the
/// generator itself breaks. That happened: `forward_deepseek2`'s MoE branch had
/// `up` and `gate` transposed, which would have made `--emit-ref` write a
/// reference 5e-1 away from llama.cpp instead of 5.6e-7. Every parity test
/// still passed, because they all compared against the *old*, correct file. This
/// is the test that would have caught it.
///
/// Skips rather than fails when the tooling is absent (no `python3`, no numpy,
/// no gguf-py), because the checked-in references remain valid without it.
#[test]
fn the_float64_oracle_reproduces_its_checked_in_references() {
    let repo = Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .unwrap()
        .to_path_buf();
    let script = repo.join("scripts/arbitrate_logits.py");
    let fixtures = Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/data/fixtures");
    if !script.exists() {
        eprintln!("skipped: {} not found", script.display());
        return;
    }
    let out_dir = std::env::temp_dir().join("slow-inference-f64-repro");
    let _ = std::fs::create_dir_all(&out_dir);

    let mut checked = 0;
    let mut skipped = Vec::new();
    for &arch in CASES {
        let gguf_arch = gguf_arch(arch);
        let refp = ref_path(arch);
        if !refp.exists() {
            continue;
        }
        let got = out_dir.join(format!("{arch}.f64.ref"));
        // `.ref` is passed as both --engine and --llama on purpose: the emitted
        // rows depend only on the fixture and the token list, so this pins the
        // prompt without contributing any comparison.
        let status = Command::new("python3")
            .arg(&script)
            .args(["--arch", gguf_arch])
            .arg("--gguf")
            .arg(fixtures.join(format!("synthetic-{arch}.gguf")))
            .arg("--engine")
            .arg(&refp)
            .arg("--llama")
            .arg(&refp)
            .arg("--emit-ref")
            .arg(&got)
            .output();
        let out = match status {
            Ok(o) if o.status.success() => o,
            Ok(o) => {
                let err = String::from_utf8_lossy(&o.stderr);
                if err.contains("No module named") || err.contains("ModuleNotFoundError") {
                    skipped.push(arch);
                    continue;
                }
                panic!("{arch}: arbitrate_logits.py failed\n{err}");
            }
            Err(_) => {
                skipped.push(arch);
                continue;
            }
        };
        assert!(
            !out.stderr.is_empty() || !out.stdout.is_empty(),
            "{arch}: no output"
        );
        let want = std::fs::read(f64_path(arch)).expect("checked-in f64 ref");
        let have = std::fs::read(&got).expect("regenerated f64 ref");
        assert_eq!(
            want.len(),
            have.len(),
            "{arch}: the regenerated float64 reference has a different length; \
             scripts/arbitrate_logits.py no longer computes what the checked-in \
             {arch}.f64.ref contains"
        );
        assert!(
            want == have,
            "{arch}: scripts/arbitrate_logits.py no longer reproduces the checked-in \
             float64 reference ({} of {} bytes differ). Either the oracle regressed \
             or the reference is stale -- find out which before regenerating, or the \
             second oracle silently stops being an oracle.",
            want.iter().zip(&have).filter(|(a, b)| a != b).count(),
            want.len()
        );
        checked += 1;
    }
    assert!(
        checked > 0,
        "skipped everything: {skipped:?} (no python3/numpy/gguf-py?)"
    );
    if !skipped.is_empty() {
        eprintln!("float64 oracle reproduction skipped for {skipped:?}");
    }
}

/// `gen_ref_logits.sh` needs a built llama.cpp. This test does not require one,
/// so it only reports availability — it exists so a tick does not waste time
/// rediscovering whether the oracle can be regenerated.
#[test]
fn reference_generator_is_available() {
    let home = std::env::var("HOME").unwrap_or_default();
    let lib = Path::new(&home).join("llama.cpp/build/bin/libllama.so");
    if !lib.exists() {
        eprintln!(
            "no {} — cannot regenerate tests/data/fixtures/*.ref \
             (the checked-in references are still used)",
            lib.display()
        );
    }
    // The generator binary is not required by this suite; touching the path
    // keeps the check honest without failing on a missing optional tool.
    let _ = Command::new("true").status();
}
